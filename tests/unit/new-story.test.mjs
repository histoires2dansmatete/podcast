import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,readFile,copyFile,rm,stat} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {spawnSync} from 'node:child_process';
const root=resolve('.');
test('Le générateur crée un brouillon complet sans modifier les histoires existantes',async(t)=>{
 const dir=await mkdtemp(join(tmpdir(),'h2-create-'));
 t.after(()=>rm(dir,{recursive:true,force:true}));
 for(const part of ['scripts','content/stories','site/assets/stories'])await mkdir(join(dir,part),{recursive:true});
 for(const s of ['new-story.mjs','story-content.mjs'])await copyFile(join(root,'scripts',s),join(dir,'scripts',s));
 await writeFile(join(dir,'package.json'),'{"type":"module"}');
 await writeFile(join(dir,'content/wordpress-stories.json'),JSON.stringify([{slug:'histoire-origine',title:'Histoire origine'}]));
 await writeFile(join(dir,'content/audio.config.json'),JSON.stringify({stories:{'histoire-origine':{src:'',platforms:{}}}}));
 await writeFile(join(dir,'site/assets/images.config.json'),JSON.stringify({globals:{logo:'assets/logo.webp'},stories:{'histoire-origine':'assets/images/old.png'}}));
 const run=()=>spawnSync(process.execPath,['scripts/new-story.mjs','--title','Le Petit Hérisson'],{cwd:dir,encoding:'utf8'});
 const result=run();assert.equal(result.status,0,result.stderr);
 const metadata=JSON.parse(await readFile(join(dir,'content/stories/le-petit-herisson.json'),'utf8'));
 assert.equal(metadata.published,false);
 assert.match(await readFile(join(dir,'content/stories/le-petit-herisson.html'),'utf8'),/Écrivez ici/);
 const images=JSON.parse(await readFile(join(dir,'site/assets/images.config.json'),'utf8'));
 assert.equal(images.stories['histoire-origine'],'assets/images/old.png');
 assert.equal(images.stories['le-petit-herisson'],'assets/images/le-petit-herisson.png');
 const audio=JSON.parse(await readFile(join(dir,'content/audio.config.json'),'utf8'));
 assert.deepEqual(audio.stories['le-petit-herisson'],{src:'',platforms:{}});
 assert.ok((await stat(join(dir,'site/assets/stories/le-petit-herisson.svg'))).isFile());
 assert.notEqual(run().status,0,'Une histoire identique ne doit pas écraser les fichiers existants');
});

/** Contrôle de l'absence d'envoi de statistiques sans accord. */
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const js=await readFile('site/assets/analytics.js','utf8');
const page=await readFile('site/confidentialite.html','utf8');
const christmas=await readFile('site/noel/index.html','utf8');
const css=await readFile('site/assets/consent.css','utf8');
assert.match(js,/if \(!allowed \|\| isLocal\) return/);
assert.match(js,/currentChoice = readChoice\(\)/);
assert.match(js,/allowed = currentChoice === 'yes'/);
assert.match(page,/id="analytics-deny"/);
assert.match(page,/id="analytics-allow"/);
assert.match(js,/id = 'analytics-choice-banner'/);
assert.match(js,/currentChoice === 'yes' \|\| currentChoice === 'no'/);
assert.match(js,/data-analytics-choice=\"no\"/);
assert.match(js,/data-analytics-choice=\"yes\"/);
assert.match(js,/window.addEventListener\('storage'/);
assert.match(christmas, /src="\/assets\/analytics\.js"/);
assert.match(css, /\.analytics-choice-banner\{/);
console.log('✓ Confidentialité : bandeau global, consentement facultatif et réversible, Noël inclus.');
